#!/usr/bin/env python3
"""
mkimage.py — convert an image into the picoOS boot splash (RGB332 C array)
============================================================================
Called by src/CMakeLists.txt when PICOOS_SPLASH_IMAGE is set.  Reads any image
Pillow can open (PNG, JPEG, BMP, ...), scales it to the Display Pack panel,
converts it to RGB332 (one byte per pixel, the framebuffer format) and writes
a C file defining

    const uint8_t picoos_splash_img[DISP_WIDTH * DISP_HEIGHT];

The array is const, so it stays in flash (XIP) and costs no SRAM.

Usage
-----
  python3 tools/mkimage.py logo.png splash_img.c --width 240 --height 135
  python3 tools/mkimage.py logo.png splash_img.c --width 320 --height 240 --fill
  python3 tools/mkimage.py logo.png out.c --width 240 --height 135 --preview p.png

Scaling: --fit (default) keeps the aspect ratio and pads with --bg,
--fill keeps the aspect ratio and crops, --stretch ignores the aspect ratio.

Requires Pillow:  pip install pillow
"""

import argparse
import os
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("mkimage.py: Pillow is required for PICOOS_SPLASH_IMAGE "
             "(pip install pillow)")


def rgb332_to_rgb888(p):
    """Expand one RGB332 byte the way display_flush_fb() does (bit
    replication to RGB565), then to 8 bits per channel."""
    r3 = (p >> 5) & 0x07
    g3 = (p >> 2) & 0x07
    b2 = p & 0x03
    r5 = (r3 << 2) | (r3 >> 1)
    g6 = (g3 << 3) | g3
    b5 = (b2 << 3) | (b2 << 1) | (b2 >> 1)
    return ((r5 << 3) | (r5 >> 2), (g6 << 2) | (g6 >> 4), (b5 << 3) | (b5 >> 2))


def rgb332_palette():
    """A 'P' image whose palette index i is RGB332 byte i, so quantizing to
    it yields framebuffer bytes directly."""
    flat = []
    for i in range(256):
        flat.extend(rgb332_to_rgb888(i))
    pal = Image.new("P", (1, 1))
    pal.putpalette(flat)
    return pal


def parse_color(text):
    text = text.lstrip("#")
    if len(text) != 6:
        raise argparse.ArgumentTypeError("colour must be RRGGBB")
    try:
        v = int(text, 16)
    except ValueError:
        raise argparse.ArgumentTypeError("colour must be RRGGBB") from None
    return ((v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF)


def scale(img, w, h, mode, bg):
    """Return a w x h RGB image according to the scaling mode."""
    if mode == "stretch":
        return img.resize((w, h), Image.Resampling.LANCZOS)

    sx = w / img.width
    sy = h / img.height
    s = min(sx, sy) if mode == "fit" else max(sx, sy)
    nw = max(1, round(img.width * s))
    nh = max(1, round(img.height * s))
    img = img.resize((nw, nh), Image.Resampling.LANCZOS)

    out = Image.new("RGB", (w, h), bg)
    out.paste(img, ((w - nw) // 2, (h - nh) // 2))   # negative offset crops
    return out


def write_c(path, data, src_name, w, h):
    lines = [
        f"/* Generated by tools/mkimage.py from {src_name} ({w}x{h}, RGB332)"
        " -- do not edit. */",
        '#include "drivers/display.h"',
        "",
        "const uint8_t picoos_splash_img[DISP_WIDTH * DISP_HEIGHT] = {",
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    lines.append("};")
    lines.append("")
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="ascii") as f:
        f.write("\n".join(lines))
    os.replace(tmp, path)   # never leave a half-written file for make


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("input", help="source image (PNG, JPEG, BMP, ...)")
    ap.add_argument("output", help="C file to write")
    ap.add_argument("--width", type=int, required=True, help="panel width")
    ap.add_argument("--height", type=int, required=True, help="panel height")
    grp = ap.add_mutually_exclusive_group()
    grp.add_argument("--fit", dest="mode", action="store_const", const="fit",
                     help="keep aspect ratio, pad with --bg (default)")
    grp.add_argument("--fill", dest="mode", action="store_const", const="fill",
                     help="keep aspect ratio, crop to cover the panel")
    grp.add_argument("--stretch", dest="mode", action="store_const",
                     const="stretch", help="ignore aspect ratio")
    ap.set_defaults(mode="fit")
    ap.add_argument("--bg", type=parse_color, default=(0, 0, 0),
                    help="padding / transparency colour RRGGBB (default 000000)")
    ap.add_argument("--no-dither", action="store_true",
                    help="nearest colour instead of Floyd-Steinberg dithering")
    ap.add_argument("--preview", metavar="PNG",
                    help="also write the RGB332 result as a PNG to check it")
    args = ap.parse_args()

    if args.width <= 0 or args.height <= 0:
        ap.error("--width and --height must be positive")

    try:
        src = Image.open(args.input)
        src.load()
    except OSError as e:
        sys.exit(f"mkimage.py: cannot read '{args.input}': {e}")

    # Flatten transparency onto the background colour.
    rgba = src.convert("RGBA")
    flat = Image.new("RGBA", rgba.size, args.bg + (255,))
    flat.alpha_composite(rgba)
    img = scale(flat.convert("RGB"), args.width, args.height, args.mode, args.bg)

    dither = Image.Dither.NONE if args.no_dither else Image.Dither.FLOYDSTEINBERG
    q = img.quantize(palette=rgb332_palette(), dither=dither)
    data = q.tobytes()
    if len(data) != args.width * args.height:
        sys.exit("mkimage.py: internal error: wrong pixel count")

    write_c(args.output, data, os.path.basename(args.input),
            args.width, args.height)

    if args.preview:
        prev = Image.new("RGB", (args.width, args.height))
        prev.putdata([rgb332_to_rgb888(b) for b in data])
        prev.save(args.preview)

    print(f"mkimage.py: {os.path.basename(args.input)} -> "
          f"{os.path.basename(args.output)} ({args.width}x{args.height}, "
          f"{len(data)} bytes, {args.mode})")


if __name__ == "__main__":
    main()
